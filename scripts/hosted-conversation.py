def schema_lean(s):
    [(kind, value)] = s.items()
    q = lambda x: json.dumps(x)
    if kind == 'text':
        lo, hi, choices = value
        return f'.text {lo} {hi} [' + ', '.join(map(q, choices)) + ']'
    if kind == 'natural': return f'.natural {value[0]} {value[1]}'
    if kind in ('identifier', 'hex'): return f'.{kind} {value}'
    if kind == 'array': return f'.array {value[0]} ({schema_lean(value[1])})'
    if kind == 'oneOf': return '.oneOf [' + ', '.join(schema_lean(v) for v in value) + ']'
    if kind == 'object': return '.object [' + ', '.join('(' + q(k) + ', ' + schema_lean(v) + ')' for k,v in value.items()) + ']'
    raise ValueError('unknown schema primitive: ' + kind)

