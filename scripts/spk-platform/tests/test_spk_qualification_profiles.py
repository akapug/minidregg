"""Exercise helper-selected limits; optional Linux integration runs the actual Rust qualifier.

Set MINIDREGG_TEST_SPK_HOST and MINIDREGG_TEST_SPK_FIXTURE to a built host and
the signed >1MiB fixture generated by spk-package-stream's qualification_fixture.
Only disposable files beneath the test operator's protected HOME are written.
"""
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[3]
HELPERS = ROOT / "deploy/spk-host"


def profile_values(helper, profile):
    source = (HELPERS / helper).read_text()
    start = source.index("case $profile in")
    block = source[start:source.index("esac", start) + 4]
    command = 'profile=$1\n' + block + '\nprintf "%s %s" "$file_limit" "$seconds"\n'
    return subprocess.run(["bash", "-c", command, "profiles", profile], capture_output=True, text=True, timeout=5)


class QualificationProfiles(unittest.TestCase):
    def test_selected_limits_cover_decoded_spools_in_both_phases(self):
        for helper in ("spk-qualify", "spk-install-phase"):
            for profile, minimum in (("standard-v1", 768 * 1024**2), ("operator-appliance-v1", 20 * 1024**3)):
                with self.subTest(helper=helper, profile=profile):
                    result = profile_values(helper, profile)
                    self.assertEqual(result.returncode, 0, result.stderr)
                    file_limit, seconds = map(int, result.stdout.split())
                    self.assertGreaterEqual(file_limit, minimum)
                    self.assertGreaterEqual(seconds, 120 if profile == "standard-v1" else 1800)
            self.assertNotEqual(profile_values(helper, "package-chosen-unlimited").returncode, 0)

    @unittest.skipUnless(os.environ.get("MINIDREGG_TEST_SPK_HOST") and os.environ.get("MINIDREGG_TEST_SPK_FIXTURE") and shutil.which("prlimit"), "requires Linux prlimit, built Rust host and signed fixture")
    def test_real_qualifier_survives_selected_fsize_and_refuses_old_limit(self):
        host = Path(os.environ["MINIDREGG_TEST_SPK_HOST"]).resolve()
        fixture = Path(os.environ["MINIDREGG_TEST_SPK_FIXTURE"]).resolve()
        with tempfile.TemporaryDirectory(prefix=".spk-qualify-regression-", dir=Path.home()) as raw:
            directory = Path(raw)
            package = directory / "package.spk"
            shutil.copyfile(fixture, package)
            package.chmod(0o600)
            self.assertGreater(package.stat().st_size, 1024**2)
            for profile in ("standard-v1", "operator-appliance-v1"):
                file_limit, _ = map(int, profile_values("spk-qualify", profile).stdout.split())
                result = subprocess.run(["prlimit", f"--fsize={file_limit}:{file_limit}", "--", str(host), "qualify", "--import-profile", profile, str(package)], capture_output=True, text=True, timeout=90)
                self.assertEqual(result.returncode, 0, result.stderr)
                qualified = json.loads(result.stdout)
                self.assertEqual(qualified["protocol"], "mini-spk-bridge-qualification-v1")
                self.assertEqual(qualified["bridgeApiPath"], "/")
            previous = subprocess.run(["prlimit", "--core=0:0", "--fsize=1048576:1048576", "--", str(host), "qualify", str(package)], capture_output=True, text=True, timeout=90)
            self.assertNotEqual(previous.returncode, 0)
            # Anonymous spools close even after SIGXFSZ; no unowned cleanup glob needed.
            self.assertEqual(sorted(p.name for p in directory.iterdir()), ["package.spk"])


if __name__ == "__main__":
    unittest.main()
